    const pixels = await page.evaluate(async () => {
      const a = await BlueprintEditor.exportPreview(data), b = await BlueprintEditor.exportPreview({...data, presentation: {...data.presentation, creatorId: '9999999999'}});
      const aa = a.getContext('2d').getImageData(0, 0, a.width, a.height).data, bb = b.getContext('2d').getImageData(0, 0, b.width, b.height).data;
      let left = 0, right = 0;
      for (let i = 0; i < aa.length; i += 4) if (aa[i] !== bb[i] || aa[i + 1] !== bb[i + 1] || aa[i + 2] !== bb[i + 2]) (i / 4 % a.width < 1908) ? left++ : right++;
      return {width: a.width, height: a.height, left, right, alpha: aa[3]};
    });
