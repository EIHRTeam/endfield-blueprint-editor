      const layout = BlueprintEditor.getData(); layout.presentation = {creatorId: null, tags: null, description: null, coverId: 'constructor'};
      const out = await BlueprintEditor.exportPreview(layout, 1920); return {width: out.width, coverId: layout.presentation.coverId};
